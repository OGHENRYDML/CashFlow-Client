#!/usr/bin/env node
import { existsSync, appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Command } from "commander";
import { createWallet, getNativeBalance, getUsdcBalance } from "../wallet.js";
import { loadConfig } from "../config.js";
import { DEFAULT_NETWORK, getNetwork } from "../networks.js";
import { sweep } from "../sweep.js";
import { createSolanaWallet, getSolBalance, getSolanaUsdcBalance } from "../solana/wallet.js";
import { DEFAULT_SOLANA_NETWORK, getSolanaNetwork } from "../solana/networks.js";
import { sweepSolana } from "../solana/sweep.js";

const program = new Command();

program
  .name("cashfl0w")
  .description("Wallets for your terminal and your agents.")
  .version("0.1.0");

program
  .command("init")
  .description("Generate fresh non-custodial wallets and write them to .env")
  .option("-n, --network <caip2>", "EVM network to configure (CAIP-2 id)", DEFAULT_NETWORK)
  .option("-s, --solana-network <caip2>", "Solana network to configure (CAIP-2 id)", DEFAULT_SOLANA_NETWORK)
  .option("--evm-only", "skip the Solana wallet", false)
  .option("--solana-only", "skip the EVM wallet", false)
  .option("-f, --force", "overwrite an existing .env", false)
  .action((opts: { network: string; solanaNetwork: string; evmOnly: boolean; solanaOnly: boolean; force: boolean }) => {
    const envPath = resolve(process.cwd(), ".env");

    if (existsSync(envPath) && !opts.force) {
      console.error(
        `.env already exists at ${envPath}. Re-run with --force to overwrite it, or delete it first.`,
      );
      process.exitCode = 1;
      return;
    }

    const lines = ["# Generated by `cashfl0w init` — never commit this file."];

    if (!opts.solanaOnly) {
      const network = getNetwork(opts.network); // throws on unknown network
      const wallet = createWallet();
      lines.push(
        `CASHFL0W_PRIVATE_KEY=${wallet.privateKey}`,
        `CASHFL0W_ADDRESS=${wallet.address}`,
        `CASHFL0W_NETWORK=${network.caip2}`,
      );
      console.log(`EVM wallet created on ${network.name}.`);
      console.log(`  Address: ${wallet.address}`);
      if (network.isTestnet) {
        console.log(`  Get Base Sepolia USDC: https://faucet.circle.com/`);
      }
    }

    if (!opts.evmOnly) {
      const solanaNetwork = getSolanaNetwork(opts.solanaNetwork); // throws on unknown network
      const solanaWallet = createSolanaWallet();
      lines.push(
        "",
        `CASHFL0W_SOLANA_PRIVATE_KEY=${solanaWallet.secretKey}`,
        `CASHFL0W_SOLANA_ADDRESS=${solanaWallet.address}`,
        `CASHFL0W_SOLANA_NETWORK=${solanaNetwork.caip2}`,
      );
      console.log(`Solana wallet created on ${solanaNetwork.name}.`);
      console.log(`  Address: ${solanaWallet.address}`);
      if (solanaNetwork.isTestnet) {
        console.log(`  Get devnet SOL: https://faucet.solana.com/  |  devnet USDC: https://faucet.circle.com/`);
      }
    }

    lines.push(
      "",
      "# Set these to the owner's own wallets before running `cashfl0w sweep`.",
      "# CASHFL0W_SWEEP_TO=0x...",
      "# CASHFL0W_SOLANA_SWEEP_TO=...",
      "",
    );
    writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });

    const gitignorePath = resolve(process.cwd(), ".gitignore");
    const gitignoreLine = ".env";
    if (existsSync(gitignorePath)) {
      const contents = readFileSync(gitignorePath, "utf8");
      if (!contents.split("\n").includes(gitignoreLine)) {
        appendFileSync(gitignorePath, `${contents.endsWith("\n") || contents === "" ? "" : "\n"}${gitignoreLine}\n`);
      }
    } else {
      writeFileSync(gitignorePath, `${gitignoreLine}\n`);
    }

    console.log(`\nPrivate keys written to ${envPath} (0600, gitignored) — never shared, never logged again.`);
    console.log(`Next: set CASHFL0W_SWEEP_TO / CASHFL0W_SOLANA_SWEEP_TO in .env, then see the README for x402 in/out.`);
  });

program
  .command("whoami")
  .description("Show the configured wallets' addresses and balances")
  .action(async () => {
    const config = loadConfig();
    if (!config.address && !config.solanaAddress) {
      console.error("No wallet configured. Run `cashfl0w init` first.");
      process.exitCode = 1;
      return;
    }

    if (config.address) {
      const [native, usdc] = await Promise.all([
        getNativeBalance(config.network, config.address),
        getUsdcBalance(config.network, config.address),
      ]);
      console.log(`EVM     ${config.address} (${config.network.name})`);
      console.log(`  Native: ${native}`);
      console.log(`  USDC:   ${usdc}`);
    }

    if (config.solanaAddress) {
      const [sol, usdc] = await Promise.all([
        getSolBalance(config.solanaNetwork, config.solanaAddress),
        getSolanaUsdcBalance(config.solanaNetwork, config.solanaAddress),
      ]);
      console.log(`Solana  ${config.solanaAddress} (${config.solanaNetwork.name})`);
      console.log(`  SOL:  ${sol}`);
      console.log(`  USDC: ${usdc}`);
    }
  });

program
  .command("sweep")
  .description("Sweep the wallet's USDC balance to the configured owner address")
  .option("-c, --chain <chain>", "which wallet to sweep: evm or solana", "evm")
  .option("--swap", "EVM only: convert native-token balance to USDC via 0x before sweeping", false)
  .option("--gas-reserve <eth>", "EVM only: native amount to leave for future gas when swapping", "0.0005")
  .option("--dry-run", "compute what would happen without sending transactions", false)
  .action(async (opts: { chain: string; swap: boolean; gasReserve: string; dryRun: boolean }) => {
    const config = loadConfig();
    try {
      if (opts.chain === "solana") {
        const result = await sweepSolana(config, opts.dryRun);
        if (!result.swept) {
          console.log(result.reason ?? "Nothing swept.");
          return;
        }
        console.log(`Swept ${result.usdcAmount} USDC to ${config.solanaSweepTo}`);
        console.log(`  Sweep tx: ${result.sweepTxHash}`);
        return;
      }

      if (opts.chain !== "evm") {
        console.error(`Unknown --chain "${opts.chain}". Use "evm" or "solana".`);
        process.exitCode = 1;
        return;
      }

      const result = await sweep(config, {
        swap: opts.swap,
        gasReserve: opts.gasReserve,
        dryRun: opts.dryRun,
      });
      if (!result.swept) {
        console.log(result.reason ?? "Nothing swept.");
        return;
      }
      console.log(`Swept ${result.usdcAmount} USDC to ${config.sweepTo}`);
      if (result.swapTxHash) console.log(`  Swap tx:  ${result.swapTxHash}`);
      console.log(`  Sweep tx: ${result.sweepTxHash}`);
    } catch (err) {
      console.error(`Sweep failed: ${(err as Error).message}`);
      process.exitCode = 1;
    }
  });

program.parseAsync(process.argv);
